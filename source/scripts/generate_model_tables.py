"""Generate LaTeX model-landscape table partials from merged_llm_database.json."""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Iterable


INTRO_FILES = {
    "slm": "intro_model_landscape_slm.tex",
    "llm": "intro_model_landscape_llm.tex",
}

APPENDIX_FILES = {
    "navigation": "model_landscape_navigation.tex",
    "slm": "model_inventory_slm_by_year.tex",
    "llm": "model_inventory_llm_by_year.tex",
}

LABELS = {
    "intro_slm": "tab:model_landscape_intro_slm",
    "intro_llm": "tab:model_landscape_intro_llm",
    "inventory_slm": "tab:model_inventory_slm_by_year",
    "inventory_llm": "tab:model_inventory_llm_by_year",
}

GENERATED_HEADER = (
    "% Auto-generated by scripts/generate_model_tables.py. Do not edit manually.\n"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate LaTeX partials for the model ecosystem tables."
    )
    parser.add_argument(
        "--input",
        default="merged_llm_database.json",
        help="Path to the source JSON inventory (default: merged_llm_database.json).",
    )
    parser.add_argument(
        "--output-dir",
        default="partials",
        help="Directory for generated LaTeX partials (default: partials).",
    )
    parser.add_argument(
        "--intro-style",
        choices=("compact", "full"),
        default="full",
        help="Intro table style: compact family summary or full family variant listing (default: full).",
    )
    return parser.parse_args()


def latex_escape(text: object) -> str:
    if text is None:
        return "--"
    text = str(text)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(ch, ch) for ch in text)


def latex_escape_url(text: str | None) -> str:
    if not text:
        return ""
    replacements = {
        "\\": r"\textbackslash{}",
        "%": r"\%",
        "#": r"\#",
        "&": r"\&",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "^": r"\textasciicircum{}",
        "~": r"\textasciitilde{}",
    }
    return "".join(replacements.get(ch, ch) for ch in text)


def href(url: str | None, text: str, fallback_text: str | None = None) -> str:
    label = latex_escape(text if text else (fallback_text or "--"))
    if not url:
        return label
    return r"\href{" + latex_escape_url(url) + "}{" + label + "}"


def compact_number(value: float, unit: str = "B") -> str:
    formatted = f"{value:.1f}".rstrip("0").rstrip(".")
    return f"{formatted}{unit}"


def unwrap_param_value(value: object) -> str | None:
    """Unwrap a parameter value that may be a plain string or a nested dict.

    Some entries in merged_llm_database.json store parameter values as nested
    dicts like ``{'total_params': '7B', 'active_params': '7B', 'architecture':
    'Transformer'}`` rather than plain strings.  This helper extracts the
    human-readable size string from either form.
    """
    if value is None:
        return None
    if isinstance(value, dict):
        # Prefer 'total_params' key; fall back to 'active_params'
        raw = value.get("total_params") or value.get("active_params")
        return str(raw).strip() if raw else None
    text = str(value).strip()
    return text if text else None


def parse_param_billions(value: object) -> float | None:
    text = unwrap_param_value(value)
    if not text or "undisclosed" in text.lower():
        return None
    match = re.search(r"(\d+(?:\.\d+)?)\s*([MBT])", text, flags=re.IGNORECASE)
    if not match:
        return None
    number = float(match.group(1))
    unit = match.group(2).upper()
    multiplier = {"M": 0.001, "B": 1.0, "T": 1000.0}[unit]
    return number * multiplier


def choose_size_value(model: dict) -> float | None:
    params = model.get("parameters", {})
    active = parse_param_billions(params.get("active_per_token"))
    total = parse_param_billions(params.get("total"))
    if params.get("is_moe") and active is not None:
        return active
    return active if active is not None else total


def render_param_cell(model: dict) -> str:
    params = model.get("parameters", {})
    total = unwrap_param_value(params.get("total")) or "Undisclosed"
    active = unwrap_param_value(params.get("active_per_token"))
    if params.get("is_moe") and active and active.strip() != total.strip():
        return latex_escape(f"{total} ({active} act.)")
    return latex_escape(total)


def format_context(value: object) -> str:
    if value in (None, "", 0):
        return "--"
    try:
        tokens = int(value)
    except (TypeError, ValueError):
        return latex_escape(value)
    if tokens % 1024 == 0 and tokens >= 1024:
        scaled = tokens // 1024
        if scaled >= 1024 and scaled % 1024 == 0:
            return compact_number(scaled / 1024, "M")
        return f"{scaled}K"
    if tokens >= 1_000_000:
        return compact_number(tokens / 1_000_000, "M")
    if tokens >= 1_000:
        return f"{round(tokens / 1_000):.0f}K"
    return str(tokens)


def summarize_modalities(modalities: Iterable[str] | None) -> str:
    if not modalities:
        return "--"
    preferred_order = ["text", "vision", "audio", "video", "code"]
    normalized = {str(part).lower() for part in modalities}
    ordered = [part.capitalize() for part in preferred_order if part in normalized]
    extras = sorted(part.capitalize() for part in normalized if part not in preferred_order)
    return "+".join(ordered + extras)


def summarize_access(values: set[str]) -> str:
    normalized = {value for value in values if value}
    if not normalized:
        return "--"
    if len(normalized) == 1:
        return next(iter(normalized))
    return "Mixed"


def summarize_notes(model: dict) -> str:
    notes: list[str] = []
    use_cases = model.get("use_cases") or []
    for item in use_cases[:2]:
        notes.append(str(item))
    languages = model.get("languages_supported")
    if languages and len(notes) < 2:
        notes.append(f"Lang: {languages}")
    pricing = model.get("pricing_usd_per_million_tokens")
    if pricing and isinstance(pricing, dict) and not notes:
        input_cost = pricing.get("input")
        output_cost = pricing.get("output")
        if input_cost is not None or output_cost is not None:
            if output_cost is not None:
                notes.append(f"Pricing: ${input_cost}/${output_cost} per 1M")
            else:
                notes.append(f"Pricing: ${input_cost} per 1M input")
    if not notes and model.get("status"):
        notes.append(str(model["status"]))
    return latex_escape("; ".join(notes) if notes else "--")


def makecell(lines: list[str]) -> str:
    filtered = [line for line in lines if line]
    if not filtered:
        return "--"
    return r"\makecell[l]{" + r" \\ ".join(filtered) + "}"


def parse_release_parts(value: object) -> tuple[int | None, int, int]:
    if value is None:
        return None, 0, 0
    text = str(value).strip()
    if not text:
        return None, 0, 0
    match = re.match(r"^(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?$", text)
    if not match:
        return None, 0, 0
    year = int(match.group(1))
    month = int(match.group(2) or 0)
    day = int(match.group(3) or 0)
    return year, month, day


def year_bucket(model: dict) -> tuple[int, str]:
    year, _, _ = parse_release_parts(model.get("release_date"))
    if year is None:
        return -1, "Undated"
    if year <= 2023:
        return 2023, "2023 and earlier"
    return year, str(year)


def release_sort_key(model: dict) -> tuple[int, int, int]:
    year, month, day = parse_release_parts(model.get("release_date"))
    if year is None:
        return -1, 0, 0
    return year, month, day


def model_sort_key(model: dict) -> tuple[str, str, float, str]:
    size_value = choose_size_value(model)
    return (
        str(model.get("developer") or ""),
        str(model.get("family") or ""),
        size_value if size_value is not None else float("inf"),
        str(model.get("name") or ""),
    )


def chronology_sort_key(model: dict) -> tuple[int, int, int, float, str]:
    year, month, day = release_sort_key(model)
    size_value = choose_size_value(model)
    return (
        -year,
        -month,
        -day,
        size_value if size_value is not None else float("inf"),
        str(model.get("name") or ""),
    )


def family_sort_key(item: tuple[str, list[dict]]) -> tuple[str, str]:
    family_name, models = item
    developer = str(models[0].get("developer") or "")
    return developer, family_name


def compute_range(models: list[dict]) -> str:
    values = [choose_size_value(model) for model in models]
    known = [value for value in values if value is not None]
    if not known:
        return "--"
    low = compact_number(min(known))
    high = compact_number(max(known))
    return low if low == high else f"{low}--{high}"


def latest_release_text(family_name: str, family_meta: dict) -> str:
    return str(family_meta.get(family_name, {}).get("latest_version") or "--")


def family_snapshot(models: list[dict]) -> str:
    return makecell(
        [
            latex_escape(f"{len(models)} variants"),
            latex_escape(compute_range(models)),
            latex_escape(f"up to {format_context(max((model.get('context_window_tokens') or 0) for model in models))}"),
            latex_escape(
                summarize_modalities(
                    sorted({modality for model in models for modality in (model.get("modalities") or [])})
                )
            ),
        ]
    )


def build_intro_table(
    model_type: str,
    models: list[dict],
    family_meta: dict,
    intro_style: str,
    source_name: str,
) -> str:
    grouped: dict[str, list[dict]] = defaultdict(list)
    for model in models:
        grouped[model["family"]].append(model)

    label = LABELS["intro_slm" if model_type == "slm" else "intro_llm"]
    title = "Small language model families" if model_type == "slm" else "Large language model families"
    target_label = LABELS["inventory_slm" if model_type == "slm" else "inventory_llm"]
    target_text = "SLM full inventory" if model_type == "slm" else "LLM full inventory"

    rows = []
    for family_name, family_models in sorted(grouped.items(), key=family_sort_key):
        meta = family_meta.get(family_name, {})
        developer = family_models[0].get("developer") or meta.get("developer") or "--"
        family_link = href(meta.get("url"), family_name)
        access = summarize_access({str(model.get("access") or "") for model in family_models})
        latest = latest_release_text(family_name, family_meta)
        if intro_style == "full":
            family_header = (
                rf"\multicolumn{{7}}{{|l|}}{{\textbf{{{latex_escape(family_name)} Family}} --- "
                + latex_escape(developer)
            )
            if latest and latest != "--":
                family_header += f" ({latex_escape(latest)})"
            if meta.get("url"):
                family_header += " " + href(meta.get("url"), "[repo]")
            family_header += r"} \\ \hline"
            rows.append(family_header)

            for model in sorted(family_models, key=chronology_sort_key):
                model_link = href(model.get("huggingface_url") or model.get("reference_url"), model.get("name") or "--")
                rows.append(
                    " & ".join(
                        [
                            model_link,
                            latex_escape(model.get("access") or access or "--"),
                            render_param_cell(model),
                            latex_escape(format_context(model.get("context_window_tokens"))),
                            latex_escape(model.get("release_date") or "--"),
                            latex_escape(summarize_modalities(model.get("modalities"))),
                            latex_escape(model.get("license") or "--"),
                        ]
                    )
                    + r" \\ \hline"
                )
        else:
            variants = str(len(family_models))
            size_range = compute_range(family_models)
            max_ctx = format_context(max((model.get("context_window_tokens") or 0) for model in family_models))
            modalities = summarize_modalities(
                sorted({modality for model in family_models for modality in (model.get("modalities") or [])})
            )
            rows.append(
                " & ".join(
                    [
                        family_link,
                        latex_escape(developer),
                        latex_escape(access),
                        latex_escape(variants),
                        latex_escape(size_range),
                        latex_escape(max_ctx),
                        latex_escape(modalities),
                        latex_escape(latest),
                    ]
                )
                + r" \\ \hline"
            )

    if intro_style == "full":
        table_body = [
            r"\begin{landscape}",
            r"{\scriptsize",
            r"\setlength{\tabcolsep}{4pt}",
            r"\begin{longtable}{|L{4.8cm}|C{1.1cm}|L{1.6cm}|C{1.3cm}|C{1.8cm}|L{2.2cm}|L{2.8cm}|}",
            rf"\caption{{Generated detailed family-grouped overview of {title.lower()} from \texttt{{{latex_escape(source_name)}}}.}}\label{{{label}}}\\",
            r"\hline",
            r"\textbf{Model} & \textbf{Access} & \textbf{Params} & \textbf{Context} & \textbf{Release} & \textbf{Modalities} & \textbf{License} \\ \hline",
            r"\endfirsthead",
            r"\caption[]{Generated detailed family-grouped overview continued.}\\",
            r"\hline",
            r"\textbf{Model} & \textbf{Access} & \textbf{Params} & \textbf{Context} & \textbf{Release} & \textbf{Modalities} & \textbf{License} \\ \hline",
            r"\endhead",
            r"\hline",
            r"\endfoot",
            r"\hline",
            r"\endlastfoot",
            *rows,
            r"\end{longtable}",
            r"}",
            r"\end{landscape}",
        ]
    else:
        table_body = [
            r"\begin{landscape}",
            r"{\scriptsize",
            r"\setlength{\tabcolsep}{4pt}",
            r"\begin{longtable}{|L{3cm}|L{2.4cm}|C{1.2cm}|C{1.1cm}|L{1.7cm}|C{1.3cm}|L{2.4cm}|L{4.5cm}|}",
            rf"\caption{{Generated overview of {title.lower()} from \texttt{{{latex_escape(source_name)}}}.}}\label{{{label}}}\\",
            r"\hline",
            r"\textbf{Family} & \textbf{Developer} & \textbf{Access} & \textbf{Variants} & \textbf{Size Range} & \textbf{Max Ctx} & \textbf{Modalities} & \textbf{Latest Release} \\ \hline",
            r"\endfirsthead",
            r"\caption[]{Generated overview continued.}\\",
            r"\hline",
            r"\textbf{Family} & \textbf{Developer} & \textbf{Access} & \textbf{Variants} & \textbf{Size Range} & \textbf{Max Ctx} & \textbf{Modalities} & \textbf{Latest Release} \\ \hline",
            r"\endhead",
            r"\hline",
            r"\endfoot",
            r"\hline",
            r"\endlastfoot",
            *rows,
            r"\end{longtable}",
            r"}",
            r"\end{landscape}",
        ]

    return GENERATED_HEADER + "\n".join(
        table_body
        + [
            r"{\footnotesize\noindent Detailed chronological inventories appear in Appendix~\ref{appendix:ecosystem}: "
            + rf"\hyperref[{target_label}]{{{target_text}}}"
            + r".\par}",
            "",
        ]
    )


def ordered_year_sections(models: list[dict]) -> list[tuple[int, str]]:
    sections = {year_bucket(model) for model in models}
    return sorted(sections, key=lambda item: (-item[0], item[1]))


def year_anchor(model_type: str, label: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
    return f"model-year-{model_type}-{slug}"


def build_year_navigation(model_type: str, models: list[dict]) -> str:
    model_label = LABELS["inventory_slm" if model_type == "slm" else "inventory_llm"]
    model_name = "SLM inventory" if model_type == "slm" else "LLM inventory"
    year_links = ", ".join(
        rf"\hyperlink{{{year_anchor(model_type, label)}}}{{{latex_escape(label)}}}"
        for _, label in ordered_year_sections(models)
    )
    return rf"\hyperref[{model_label}]{{{model_name}}}: {year_links}"


def build_navigation_fragment(slm_models: list[dict], llm_models: list[dict]) -> str:
    return GENERATED_HEADER + "\n".join(
        [
            r"{\footnotesize",
            r"\noindent\textbf{Chronology navigation.} "
            + build_year_navigation("slm", slm_models)
            + r". "
            + build_year_navigation("llm", llm_models)
            + r".\par}",
            "",
        ]
    )


def build_inventory_table(
    model_type: str,
    models: list[dict],
    family_meta: dict,
    source_name: str,
) -> str:
    title = "small language model" if model_type == "slm" else "large language model"
    label = LABELS["inventory_slm" if model_type == "slm" else "inventory_llm"]

    by_year: dict[tuple[int, str], list[dict]] = defaultdict(list)
    for model in models:
        by_year[year_bucket(model)].append(model)

    body: list[str] = []
    for _, year_label in ordered_year_sections(models):
        anchor = year_anchor(model_type, year_label)
        year_models = by_year[next(section for section in by_year if section[1] == year_label)]
        if body:
            body.append(r"\addlinespace[3pt]")
        body.append(
            rf"\multicolumn{{8}}{{@{{}}l}}{{\hypertarget{{{anchor}}}{{\textbf{{{latex_escape(year_label)}}}}}}} \\ \midrule"
        )

        grouped: dict[str, list[dict]] = defaultdict(list)
        for model in sorted(year_models, key=chronology_sort_key):
            grouped[model["family"]].append(model)

        for family_name, family_models in sorted(grouped.items(), key=family_sort_key):
            meta = family_meta.get(family_name, {})
            developer = family_models[0].get("developer") or meta.get("developer") or "--"
            latest = meta.get("latest_version")
            family_header = (
                rf"\multicolumn{{8}}{{@{{}}l}}{{\textit{{{latex_escape(family_name)}}} --- {latex_escape(developer)}"
            )
            if latest:
                family_header += f" ({latex_escape(latest)})"
            if meta.get("url"):
                family_header += " " + href(meta.get("url"), "[family page]")
            family_header += r"} \\*"
            body.append(family_header)

            for model in sorted(family_models, key=chronology_sort_key):
                model_link = href(model.get("huggingface_url") or model.get("reference_url"), model.get("name") or "--")
                row = " & ".join(
                    [
                        model_link,
                        latex_escape(model.get("access") or "--"),
                        render_param_cell(model),
                        latex_escape(format_context(model.get("context_window_tokens"))),
                        latex_escape(summarize_modalities(model.get("modalities"))),
                        latex_escape(model.get("license") or "--"),
                        latex_escape(model.get("release_date") or "--"),
                        summarize_notes(model),
                    ]
                )
                body.append(row + r" \\")

    return GENERATED_HEADER + "\n".join(
        [
            r"\begin{landscape}",
            r"{\scriptsize",
            r"\setlength{\tabcolsep}{4pt}",
            r"\renewcommand{\arraystretch}{1.15}",
            r"\begin{longtable}{@{}L{3.3cm}C{1.05cm}L{1.75cm}C{1.15cm}L{2.25cm}L{2.4cm}C{1.6cm}L{3.9cm}@{}}",
            rf"\caption{{Generated chronological {title} inventory from \texttt{{{latex_escape(source_name)}}}, grouped by release year and family.}}\label{{{label}}}\\",
            r"\toprule",
            r"\textbf{Model} & \textbf{Access} & \textbf{Params} & \textbf{Context} & \textbf{Modalities} & \textbf{License} & \textbf{Release} & \textbf{Notes} \\ \midrule",
            r"\endfirsthead",
            rf"\caption[]{{Generated chronological {title} inventory continued.}}\\",
            r"\toprule",
            r"\textbf{Model} & \textbf{Access} & \textbf{Params} & \textbf{Context} & \textbf{Modalities} & \textbf{License} & \textbf{Release} & \textbf{Notes} \\ \midrule",
            r"\endhead",
            r"\midrule \multicolumn{8}{r@{}}{\footnotesize\itshape continued on next page} \\",
            r"\endfoot",
            r"\bottomrule",
            r"\endlastfoot",
            *body,
            r"\end{longtable}",
            r"}",
            r"\end{landscape}",
            "",
        ]
    )


def load_inventory(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def write_text(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8", newline="\n")


def main() -> None:
    args = parse_args()
    input_path = Path(args.input)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    inventory = load_inventory(input_path)
    source_name = input_path.name
    family_meta = {family["name"]: family for family in inventory.get("families", [])}
    slm_models = list(inventory.get("models", {}).get("slm", []))
    llm_models = list(inventory.get("models", {}).get("llm", []))

    write_text(
        output_dir / INTRO_FILES["slm"],
        build_intro_table("slm", slm_models, family_meta, args.intro_style, source_name),
    )
    write_text(
        output_dir / INTRO_FILES["llm"],
        build_intro_table("llm", llm_models, family_meta, args.intro_style, source_name),
    )
    write_text(output_dir / APPENDIX_FILES["navigation"], build_navigation_fragment(slm_models, llm_models))
    write_text(
        output_dir / APPENDIX_FILES["slm"],
        build_inventory_table("slm", slm_models, family_meta, source_name),
    )
    write_text(
        output_dir / APPENDIX_FILES["llm"],
        build_inventory_table("llm", llm_models, family_meta, source_name),
    )


if __name__ == "__main__":
    main()
